# Starter Code

These files are the foundation for the Multiverse PhilBill MVP.

- `schema.sql` → Run this in your Supabase SQL editor
- `types.ts` → TypeScript types
- `supabase.ts` → Supabase client
- `SwipeCard.tsx` → Basic swipe card component

To use:
1. Create a Next.js app
2. Copy these files into the proper folders
3. Set up Supabase and add your keys
